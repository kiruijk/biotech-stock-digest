async function buildStockData(symbol, previous) {
  const info = STOCK_INFO[symbol];
  const quote = await withRetry(() => yahooFinance.quote(symbol));
  if (quote?.regularMarketPrice == null) throw new Error('no price in quote');

  const news = await getNews(symbol, info.name);
  // Price move since the editorial profile was last reviewed (for review-queue.js)
  const reviewed = readProfile(symbol)?.reviewed;
  const extraTargets = reviewed ? { sinceReviewed: new Date(`${reviewed}T23:59:59Z`) } : {};
  const { returns, history } = await getReturns(symbol, quote, quote.regularMarketPrice, extraTargets);
  if (history && history.length) writeHistory(symbol, history);
  const financials = await getFinancials(symbol, quote.financialCurrency);

  // Company info changes rarely; reuse the previous copy if this fetch fails
  let companyInfo;
  try {
    companyInfo = await getCompanyInfo(symbol);
  } catch (err) {
    console.warn(`    ⚠️  Could not fetch company info for ${symbol}: ${err.message}`);
    companyInfo = { company: previous?.company || {}, insiders: previous?.insiders || [], nextEarnings: previous?.nextEarnings || null };
  }

  return {
    symbol,
    name: info.name,
    themes: info.themes,
    price: round2(quote.regularMarketPrice),
    change: quote.regularMarketPreviousClose != null ? round2(quote.regularMarketPrice - quote.regularMarketPreviousClose) : null,
    changePercent: round2(quote.regularMarketChangePercent ?? null),
    marketCap: quote.marketCap ?? null,
    updatedAt: new Date().toISOString(),
    ...financials,
    ...returns,
    ...companyInfo,
    news
  };
}

async function updateAll() {
  const stockData = {};
  const previousData = readPreviousData();

  // --render-only rebuilds the HTML from the last run's data without fetching anything,
  // for iterating on templates: `node update-stocks.js --render-only`
  const renderOnly = process.argv.includes('--render-only');
  if (renderOnly) console.log('Render-only: using data/market.json, no fetching');
  else console.log('Fetching stock data...');
  for (const symbol of renderOnly ? [] : STOCKS) {
    console.log(`  ${symbol}...`);
    try {
      stockData[symbol] = await buildStockData(symbol, previousData[symbol]);
    } catch (err) {
      console.warn(`  Failed to fetch ${symbol}: ${err.message}`);
      const prev = previousData[symbol];
      if (prev) {
        console.warn(`  Keeping last good data for ${symbol} (marked stale)`);
        stockData[symbol] = {
          ...prev,
          name: STOCK_INFO[symbol].name,
          themes: STOCK_INFO[symbol].themes,
          stale: true,
          staleSince: prev.staleSince || prev.updatedAt || null
        };
      }
    }
  }

  if (renderOnly) {
    Object.assign(stockData, previousData);
  }
  for (const d of Object.values(stockData)) {
    d.news = (d.news || []).map(n => ({ ...n, title: cleanNewsTitle(n) }));
    d.materialNews = updateMaterialNews(d, previousData[d.symbol], readProfile(d.symbol)?.reviewed);
  }
  if (!renderOnly) {
    // Full data (company info, insiders, all news) for the next run and for profile pages
    fs.writeFileSync(MARKET_FILE, JSON.stringify(stockData, null, 2) + '\n');
    console.log(`\nWrote ${MARKET_FILE}`);
  }

  // Homepage gets a lighter copy: no company details or insider tables, 3 news items
  const coveredSymbols = new Set(STOCKS.filter(s => readProfile(s)));
  const homepageData = Object.fromEntries(Object.entries(stockData).map(([symbol, d]) => {
    const { company, insiders, news, sinceReviewed, cashOverrideSuperseded, materialNews, ...rest } = d;
    return [symbol, { ...rest, covered: coveredSymbols.has(symbol), news: (news || []).slice(0, 3), spark: sparklines(readHistory(symbol), d.price) }];
  }));
  console.log('Updating index.html...');
  let indexHTML = fs.readFileSync('index.html', 'utf8');
  const indent = (json) => json.replace(/^/gm, '      ').trim();
  indexHTML = indexHTML
    .replace(/const demoData = \{[\s\S]*?^\s*\};/m, () => `const demoData = ${indent(compactNumberArrays(JSON.stringify(homepageData, null, 2)))};`)
    .replace(/const THEMES = \[[^\]]*\];/, `const THEMES = ${JSON.stringify(UNIVERSE.themes)};`)
    .replace(/const THEME_INFO = [\s\S]*?; \/\/ end THEME_INFO/, `const THEME_INFO = ${JSON.stringify(themeInfo())}; // end THEME_INFO`)
    // Shared site navigation, footer links and their CSS (from templates/site.js)
    .replace(/<!-- SITE_NAV -->[\s\S]*?<!-- \/SITE_NAV -->/, () => `<!-- SITE_NAV -->\n${renderNav('', UNIVERSE.themes, 'dashboard')}\n  <!-- /SITE_NAV -->`)
    .replace(/<!-- SITE_FOOTER -->[\s\S]*?<!-- \/SITE_FOOTER -->/, () => `<!-- SITE_FOOTER -->\n${renderFooterLinks('', UNIVERSE.themes)}\n    <!-- /SITE_FOOTER -->`)
    .replace(/\/\* SITE_NAV_CSS \*\/[\s\S]*?\/\* \/SITE_NAV_CSS \*\//, () => `/* SITE_NAV_CSS */${NAV_CSS.replace(/^/gm, '    ')}    /* /SITE_NAV_CSS */`)
    // SEO head tags and crawlable static copies of the stock list and news feed
    .replace(/<!-- SEO_HEAD -->[\s\S]*?<!-- \/SEO_HEAD -->/, () => `<!-- SEO_HEAD -->\n${renderHomeHead(SITE)}\n  <!-- /SEO_HEAD -->`)
    .replace(/<!-- STATIC_STOCKS -->[\s\S]*?<!-- \/STATIC_STOCKS -->/, () => `<!-- STATIC_STOCKS -->${renderStaticStocks(Object.values(stockData))}<!-- /STATIC_STOCKS -->`)
    .replace(/<!-- STATIC_NEWS -->[\s\S]*?<!-- \/STATIC_NEWS -->/, () => `<!-- STATIC_NEWS -->${renderStaticNews(Object.values(stockData))}<!-- /STATIC_NEWS -->`);
  fs.writeFileSync('index.html', indexHTML);

  // Profile pages are regenerated in full from the template
  fs.mkdirSync(PAGES_DIR, { recursive: true });
  for (const symbol of STOCKS) {
    if (!stockData[symbol]) continue;
    fs.writeFileSync(`${PAGES_DIR}/${symbol.toLowerCase()}.html`, renderProfile(stockData[symbol], readProfile(symbol), UNIVERSE.themes, SITE.url, chartSeries(readHistory(symbol))));
  }
  console.log(`Rendered ${Object.keys(stockData).length} profile pages (${coveredSymbols.size} covered, ${Object.keys(stockData).length - coveredSymbols.size} tracked)`);

  // Theme pages: science background from data/themes + live data for the theme's stocks
  fs.mkdirSync(THEME_PAGES_DIR, { recursive: true });
  const profiles = Object.fromEntries(STOCKS.map(s => [s, readProfile(s)]));
  for (const theme of UNIVERSE.themes) {
    const file = `${THEME_DIR}/${themeSlug(theme)}.json`;
    const content = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : null;
    const members = STOCKS.filter(s => stockData[s] && STOCK_INFO[s].themes.includes(theme)).map(s => stockData[s]);
    fs.writeFileSync(`${THEME_PAGES_DIR}/${themeSlug(theme)}.html`, renderTheme(theme, content, members, profiles, UNIVERSE.themes, SITE.url));
  }
  console.log(`Rendered ${UNIVERSE.themes.length} theme pages`);

  fs.writeFileSync('calendar.html', renderCalendar(STOCKS.filter(s => stockData[s]).map(s => stockData[s]), profiles, UNIVERSE.themes, SITE.url));
  console.log('Rendered calendar.html');

  // sitemap.xml + robots.txt so search engines can find every page
  const today = new Date().toISOString().slice(0, 10);
  const pages = ['', 'calendar.html',
    ...UNIVERSE.themes.map(t => `${THEME_PAGES_DIR}/${themeSlug(t)}.html`),
    ...STOCKS.filter(s => stockData[s]).map(s => `${PAGES_DIR}/${s.toLowerCase()}.html`)];
  fs.writeFileSync('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${pages.map(p => `  <url><loc>${SITE.url}${p}</loc><lastmod>${today}</lastmod><changefreq>daily</changefreq></url>`).join('\n')}
</urlset>
`);
  fs.writeFileSync('robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${SITE.url}sitemap.xml\n`);
  console.log(`Wrote sitemap.xml (${pages.length} pages) and robots.txt`);

  // Remove generated pages for stocks no longer in the universe
  const current = new Set(STOCKS.map(s => `${s.toLowerCase()}.html`));
  for (const file of fs.readdirSync(PAGES_DIR)) {
    if (!file.endsWith('.html') || current.has(file)) continue;
    if (fs.readFileSync(`${PAGES_DIR}/${file}`, 'utf8').includes(GENERATED_MARKER)) {
      fs.unlinkSync(`${PAGES_DIR}/${file}`);
      console.log(`  Removed ${PAGES_DIR}/${file} (no longer in data/universe.json)`);
    }
  }

  console.log('\n✅ Stock data updated!');
  for (const symbol of STOCKS) {
    const d = stockData[symbol];
    if (d) console.log(`${symbol}: $${d.price} ${d.changePercent >= 0 ? '+' : ''}${d.changePercent}% | YTD: ${d.ytd == null ? '—' : d.ytd + '%'}${d.stale ? ' (STALE)' : ''}`);
    else console.log(`${symbol}: MISSING (fetch failed and no previous data)`);
  }
}

// Run
updateAll().catch(err => {
  console.error('Fatal error:', err);
  process.exit(1);
});
