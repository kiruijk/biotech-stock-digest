// Material headlines published after the profile's review date. Carried forward between
// runs (news lists only keep the latest few items) until the profile's `reviewed` date moves
// past them, so review-queue.js can list them.
function updateMaterialNews(stock, previous, reviewed) {
  if (!reviewed) return [];
  const isNew = (n) => (n.date || '').slice(0, 10) > reviewed;
  const found = [...(previous?.materialNews || []), ...(stock.news || []).filter(n => isMaterialNews(n.title))]
    .filter(isNew);
  const byUrl = new Map(found.map(n => [n.url, { title: n.title, source: n.source, date: n.date, url: n.url }]));
  return [...byUrl.values()].sort((a, b) => new Date(b.date) - new Date(a.date)).slice(0, 10);
}

// Google News titles end with " - <source>", which the pages already show separately
function cleanNewsTitle(item) {
  const suffix = ` - ${item.source}`;
  const title = item.title || '';
  return title.toLowerCase().endsWith(suffix.toLowerCase()) ? title.slice(0, -suffix.length).trim() : title;
}

// Combine news from multiple sources
async function getNews(symbol, company) {
  try {
    const yahooNews = await getYahooNews(symbol);
    const googleNews = await getGoogleNews(company);
    const allNews = [...yahooNews, ...googleNews].filter(item => !isLowValueNews(item));

    if (allNews.length === 0) {
      console.warn(`⚠️  No news found for ${symbol}`);
      return [];
    }

    // Remove duplicates and sort by date (newest first)
    const uniqueNews = Array.from(new Map(allNews.map(item => [item.title, item])).values());
    uniqueNews.sort((a, b) => new Date(b.date) - new Date(a.date));

    // Profile pages list up to 6; the homepage feed uses the first 3
    const topNews = uniqueNews.slice(0, 6);
    console.log(`✓ Fetched ${topNews.length} articles from Yahoo Finance & Google News for ${symbol}`);
    if (topNews.length > 0) {
      console.log(`  Latest: ${topNews[0].title} (${topNews[0].date})`);
    }

    return topNews;
  } catch (err) {
    console.warn(`⚠️  Error fetching news for ${symbol}: ${err.message}`);
    return [];
  }
}

// Round to 2 decimals, passing null/undefined through as null
const round2 = (n) => (n == null ? null : parseFloat(n.toFixed(2)));
// 4 significant digits is plenty for chart points and keeps the files small
const round4 = (n) => (n == null ? null : parseFloat(n.toPrecision(4)));

// Return periods shown on the dashboard. Each maps a field name to the date the
// return is measured from; 1D comes straight from the quote.
const RETURN_PERIODS = {
  fiveDay: (now) => daysAgo(now, 7),  // 7 calendar days covers 5 trading days
  oneMonth: (now) => monthsAgo(now, 1),
  sixMonth: (now) => monthsAgo(now, 6),
  ytd: (now) => new Date(now.getFullYear() - 1, 11, 31),  // last close of prior year
  oneYear: (now) => monthsAgo(now, 12),
  threeYear: (now) => monthsAgo(now, 36),
  fiveYear: (now) => monthsAgo(now, 60),
  tenYear: (now) => monthsAgo(now, 120)
};

function daysAgo(now, n) {
  const d = new Date(now);
  d.setDate(d.getDate() - n);
  return d;
}

function monthsAgo(now, n) {
  const d = new Date(now);
  d.setMonth(d.getMonth() - n);
  return d;
}

// Fetch returns from Yahoo Finance for 1D plus every period in RETURN_PERIODS.
// Also returns the daily close history (oldest → newest) used for charts.
async function getReturns(symbol, quote, currentPrice, extraTargets = {}) {
  // null means "unavailable" (rendered as —), distinct from a real 0% return
  const returns = { oneDay: round2(quote.regularMarketChangePercent) };
  for (const field of Object.keys(RETURN_PERIODS)) returns[field] = null;
  let history = null;

  try {
    const now = new Date();
    const targets = {
      ...Object.fromEntries(Object.entries(RETURN_PERIODS).map(([field, getDate]) => [field, getDate(now)])),
      ...extraTargets
    };
    // Fetch a little before the oldest target so there's a close on or before it
    const historyStart = daysAgo(new Date(Math.min(...Object.values(targets))), 10);
    const historicalData = await getHistoricalData(symbol, historyStart);

    if (historicalData && historicalData.length > 0) {
      // Sort oldest → newest
      const sorted = historicalData
        .filter(q => q.close != null)
        .sort((a, b) => new Date(a.date) - new Date(b.date));

      // Most recent close on or before the target date. Returns null when the stock's
      // history doesn't reach back that far (e.g. a recent IPO), rather than silently
      // measuring from the first trading day.
      const closeAt = (target) => {
        const q = [...sorted].reverse().find(q => new Date(q.date) <= target);
        return q ? q.close : null;
      };

      for (const [field, target] of Object.entries(targets)) {
        const pastClose = closeAt(target);
        if (pastClose) returns[field] = round2(((currentPrice - pastClose) / pastClose) * 100);
      }
      history = sorted.map(q => [new Date(q.date).toISOString().slice(0, 10), round4(q.close)]);
    }

    const fmt = (v) => (v == null ? '—' : `${v}%`);
    console.log(`    1D: ${fmt(returns.oneDay)} | 5D: ${fmt(returns.fiveDay)} | 1M: ${fmt(returns.oneMonth)} | 6M: ${fmt(returns.sixMonth)} | YTD: ${fmt(returns.ytd)} | 1Y: ${fmt(returns.oneYear)} | 3Y: ${fmt(returns.threeYear)} | 5Y: ${fmt(returns.fiveYear)} | 10Y: ${fmt(returns.tenYear)}`);
  } catch (err) {
    console.warn(`⚠️  Error fetching returns for ${symbol}: ${err.message}`);
  }
  return { returns, history };
}

// Hand-entered cash figures (from the 10-Q) for companies where Yahoo's balance sheet
// is incomplete. Used only while at least as recent as Yahoo's latest quarter —
// update the amount and asOf date each quarter.
const cashOverrides = {
  IOVA: { amount: 304e6, asOf: '2026-06-30' },   // company-reported ~$304M; Yahoo has only $110.8M cash & equivalents
  PRME: { amount: 108.8e6, asOf: '2026-06-30' }  // Yahoo omits Prime's marketable securities
};

const fxRates = {};

// USD per unit of `currency`, e.g. EUR → ~1.14. Null if the rate can't be fetched.
async function getUsdRate(currency) {
  if (currency === 'USD') return 1;
  if (!(currency in fxRates)) {
    try {
      const fx = await yahooFinance.quote(`${currency}USD=X`);
      fxRates[currency] = fx?.regularMarketPrice ?? null;
    } catch (err) {
      console.warn(`    ⚠️  Could not fetch ${currency}/USD rate: ${err.message}`);
      fxRates[currency] = null;
    }
  }
  return fxRates[currency];
}

// Cash and burn from Yahoo's quarterly statements:
// - cash = cash, equivalents & short-term investments + long-term marketable securities
//   (excludes strategic equity stakes), matching what companies report in earnings releases
// - burn = latest quarter's operating cash outflow ÷ 3 (actual cash spent, unlike net loss
//   which includes non-cash items like stock comp and warrant revaluations)
async function getFinancials(symbol, currency) {
  const result = { cashPosition: null, cashAsOf: null, monthlyBurn: null, cashFlowPositive: false };

  try {
    const rows = await withRetry(() => yahooFinance.fundamentalsTimeSeries(symbol, {
      period1: daysAgo(new Date(), 400),
      type: 'quarterly',
      module: 'all'
    }));
    const latest = (field) => [...rows].reverse().find(r => r[field] != null);
    const fx = await getUsdRate(currency || 'USD');

    const bs = latest('cashCashEquivalentsAndShortTermInvestments');
    if (bs && fx) {
      const longTerm = bs.investmentinFinancialAssets ?? bs.investmentsAndAdvances ?? 0;
      result.cashPosition = (bs.cashCashEquivalentsAndShortTermInvestments + longTerm) * fx;
      result.cashAsOf = new Date(bs.date).toISOString().slice(0, 10);
    }

    const cf = latest('operatingCashFlow');
    if (cf && fx) {
      if (cf.operatingCashFlow < 0) result.monthlyBurn = (-cf.operatingCashFlow * fx) / 3;
      else result.cashFlowPositive = true;
    }
  } catch (err) {
    console.warn(`    ⚠️  Could not fetch financials for ${symbol}: ${err.message}`);
  }

  const override = cashOverrides[symbol];
  if (override && (!result.cashAsOf || override.asOf >= result.cashAsOf)) {
    result.cashPosition = override.amount;
    result.cashAsOf = override.asOf;
  } else if (override) {
    // Yahoo now has a newer quarter than the hand-entered figure. Yahoo's number is used,
    // but it was incomplete for this company last time — flag it so the override gets
    // refreshed from the new 10-Q (check-freshness.js fails the run on this).
    result.cashOverrideSuperseded = { overrideAsOf: override.asOf, yahooAsOf: result.cashAsOf };
    console.warn(`    ⚠️  cashOverrides.${symbol} (as of ${override.asOf}) is older than Yahoo's ${result.cashAsOf} — update it from the latest 10-Q`);
  }

  const m = (v) => (v == null ? '—' : `$${(v / 1e6).toFixed(1)}M`);
  console.log(`    Cash: ${m(result.cashPosition)} (as of ${result.cashAsOf ?? '—'}) | Burn: ${result.cashFlowPositive ? 'cash-flow positive' : `${m(result.monthlyBurn)}/mo`}`);
  return result;
}

// Company description, leadership and insider trades (Form 4) from Yahoo
async function getCompanyInfo(symbol) {
  const summary = await withRetry(() => yahooFinance.quoteSummary(symbol, { modules: ['assetProfile', 'insiderTransactions', 'calendarEvents'] }));
  const ap = summary.assetProfile || {};
  return {
    company: {
      summary: ap.longBusinessSummary || null,
      city: ap.city || null,
      state: ap.state || null,
      country: ap.country || null,
      employees: ap.fullTimeEmployees || null,
      website: ap.website || null,
      officers: (ap.companyOfficers || []).slice(0, 5).map(o => ({
        name: cleanOfficerName(o.name),
        title: o.title
      }))
    },
    insiders: parseInsiders(summary.insiderTransactions?.transactions),
    nextEarnings: parseNextEarnings(summary.calendarEvents?.earnings)
  };
}

// Next scheduled earnings date, or null if Yahoo only has one that's already passed
function parseNextEarnings(earnings) {
  const today = new Date().toISOString().slice(0, 10);
  const date = (earnings?.earningsDate || [])
    .map(d => new Date(d).toISOString().slice(0, 10))
    .find(d => d >= today);
  return date ? { date, estimated: Boolean(earnings.isEarningsDateEstimate) } : null;
}

const cleanOfficerName = (name) => String(name || '').replace(/^(Mr|Ms|Mrs|Miss)\.?\s+/, '').replace(/\s+/g, ' ').trim();

// Form 4 transactions, newest first. Rows without a transaction description are
// holdings reports rather than trades, so they're skipped.
function parseInsiders(transactions) {
  return (transactions || [])
    .filter(t => t.transactionText && t.startDate)
    .sort((a, b) => new Date(b.startDate) - new Date(a.startDate))
    .slice(0, 20)
    .map(t => ({
      name: formatInsiderName(t.filerName),
      relation: formatRelation(t.filerRelation),
      date: new Date(t.startDate).toISOString().slice(0, 10),
      type: classifyTransaction(t.transactionText),
      shares: t.shares ?? null,
      value: t.value || null
    }));
}

function classifyTransaction(text) {
  if (/purchase/i.test(text)) return 'BUY';
  if (/sale/i.test(text)) return 'SELL';
  if (/award|grant/i.test(text)) return 'AWARD';
  if (/exercise|conversion/i.test(text)) return 'EXERCISE';
  if (/gift/i.test(text)) return 'GIFT';
  return 'OTHER';
}

const ENTITY_WORDS = /\b(L\.?L\.?C\.?|L\.?P\.?|INC\.?|LTD\.?|PLC|FUND|CAPITAL|INVESTMENTS?|INVESTORS|PARTNERS|VENTURES?|MANAGEMENT|ADVISORS|HOLDINGS|TRUST|COOPERATIEF|GROUP|FOUNDATION)\b/i;
const NAME_SUFFIXES = { JR: 'Jr.', SR: 'Sr.', II: 'II', III: 'III', IV: 'IV' };

const titleWord = (w) => w.toLowerCase().replace(/(^|[-'])([a-z])/g, (m, p, c) => p + c.toUpperCase());

// Yahoo gives filer names as "LAST FIRST MIDDLE" in capitals; entities are left in order
function formatInsiderName(raw) {
  const name = String(raw || '').trim().replace(/\s+/g, ' ');
  if (ENTITY_WORDS.test(name) || /^FMR\b/.test(name)) {
    // Keep short tokens like "RA", "GV", "LLC", "L.P." in capitals
    return name.split(' ').map(w => (w.replace(/[.,]/g, '').length <= 3 ? w : titleWord(w))).join(' ');
  }
  const parts = name.split(' ');
  const suffixes = [];
  while (parts.length > 2 && NAME_SUFFIXES[parts[parts.length - 1].replace(/\./g, '')]) {
    suffixes.unshift(NAME_SUFFIXES[parts.pop().replace(/\./g, '')]);
  }
  const [last, ...rest] = parts;
  return [...rest.map(titleWord), titleWord(last), ...suffixes].join(' ');
}

const formatRelation = (rel) => String(rel || '')
